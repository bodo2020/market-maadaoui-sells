declare
  v_id uuid;
  v_merchant_tenant uuid;
  v_row jsonb;
begin
  if not public.can_manage_business_structure_v1(p_tenant_id) then raise exception using errcode='42501',message='BUSINESS_STRUCTURE_MANAGER_REQUIRED'; end if;
  if p_group_type not in ('region','operations','franchise_network','marketplace_network','custom') then raise exception using errcode='22023',message='INVALID_BRANCH_GROUP_TYPE'; end if;
  if nullif(btrim(coalesce(p_code,'')),'') is null or nullif(btrim(coalesce(p_name,'')),'') is null then raise exception using errcode='22023',message='GROUP_CODE_AND_NAME_REQUIRED'; end if;
  if p_merchant_id is not null then
    select m.tenant_id into v_merchant_tenant from public.merchants m where m.id=p_merchant_id;
    if v_merchant_tenant is distinct from p_tenant_id then raise exception using errcode='22023',message='GROUP_MERCHANT_TENANT_MISMATCH'; end if;
  end if;

  insert into private.branch_groups_v1(tenant_id,merchant_id,code,name,group_type,metadata,created_by,updated_by)
  values(p_tenant_id,p_merchant_id,lower(btrim(p_code)),btrim(p_name),p_group_type,coalesce(p_metadata,'{}'::jsonb),auth.uid(),auth.uid())
  returning id into v_id;

  select to_jsonb(g) into v_row from private.branch_groups_v1 g where g.id=v_id;
  insert into private.business_structure_audit_v1(tenant_id,entity_type,entity_id,action,after_state,actor_user_id)
  values(p_tenant_id,'branch_group',v_id,'create',v_row,auth.uid());
  return v_row;
end;
$$;

