create or replace function public.get_business_structure_v1(p_tenant_id uuid default null)
returns jsonb
language plpgsql
stable
security definer
set search_path=''
as $$
declare
  v_tenant_id uuid:=p_tenant_id;
  v_tenant jsonb;
  v_summary jsonb;
  v_merchants jsonb;
  v_groups jsonb;
begin
  if v_tenant_id is null then
    if public.is_super_admin() then
      select t.id into v_tenant_id
      from public.tenants t
      order by case when coalesce((t.settings->>'is_platform_tenant')::boolean,false) then 0 else 1 end, t.created_at
      limit 1;
    else
      select tu.tenant_id into v_tenant_id
      from public.tenant_users tu
      where tu.user_id=auth.uid() and coalesce(tu.is_active,true)
      order by tu.created_at
      limit 1;
    end if;
  end if;

  if v_tenant_id is null or not public.has_tenant_access(v_tenant_id) then
    raise exception using errcode='42501',message='TENANT_ACCESS_REQUIRED';
  end if;

  select jsonb_build_object(
    'id',t.id,'name',t.name,'subdomain',t.subdomain,'status',t.status,
    'logo_url',t.logo_url,'country',t.country,'city',t.city
  ) into v_tenant
  from public.tenants t where t.id=v_tenant_id;

  select jsonb_build_object(
    'merchant_count',count(distinct m.id),
    'branch_count',count(b.id),
    'owned_branch_count',count(b.id) filter(where m.merchant_type='owned'),
    'franchise_branch_count',count(b.id) filter(where m.merchant_type='franchise'),
    'marketplace_branch_count',count(b.id) filter(where m.merchant_type='partner'),
    'active_branch_count',count(b.id) filter(where coalesce(b.active,false)),
    'online_branch_count',count(b.id) filter(where private.branch_channel_effective_enabled_v1(b.id,'online_sales')),
    'delivery_branch_count',count(b.id) filter(where private.branch_channel_effective_enabled_v1(b.id,'delivery'))
  ) into v_summary
  from public.merchants m
  left join public.branches b on b.merchant_id=m.id
  where m.tenant_id=v_tenant_id;

  select coalesce(jsonb_agg(
    jsonb_build_object(
      'id',m.id,'code',m.code,'name',m.name,'merchant_type',m.merchant_type,'status',m.status,
      'contact_name',m.contact_name,'phone',m.phone,'email',m.email,
      'customer_published_at',m.customer_published_at,
      'branch_count',(select count(*) from public.branches bx where bx.merchant_id=m.id),
      'branches',coalesce((
        select jsonb_agg(
          jsonb_build_object(
            'id',b.id,'name',b.name,'code',b.code,'address',b.address,'active',b.active,
            'category',b.category::text,'branch_type',b.branch_type::text,
            'delivery_enabled',b.delivery_enabled,'marketplace_customer_enabled',b.marketplace_customer_enabled,
            'opens_at',b.opens_at,'closes_at',b.closes_at,
            'latitude',b.latitude,'longitude',b.longitude,
            'channels',(select jsonb_object_agg(c.channel,private.branch_channel_runtime_v1(b.id,c.channel))
                        from (values ('pos'::text),('online_sales'),('customer_app'),('marketplace'),('delivery'),('pickup')) c(channel)),
            'groups',coalesce((select jsonb_agg(jsonb_build_object('id',g.id,'code',g.code,'name',g.name,'group_type',g.group_type) order by g.name)
                               from private.branch_group_members_v1 gm join private.branch_groups_v1 g on g.id=gm.group_id
                               where gm.branch_id=b.id and g.active),'[]'::jsonb)
          ) order by b.name
        ) from public.branches b where b.merchant_id=m.id
      ),'[]'::jsonb)
    ) order by case m.merchant_type when 'owned' then 0 when 'franchise' then 1 else 2 end,m.name
  ),'[]'::jsonb) into v_merchants
  from public.merchants m
  where m.tenant_id=v_tenant_id;

  select coalesce(jsonb_agg(
    jsonb_build_object(
      'id',g.id,'code',g.code,'name',g.name,'group_type',g.group_type,'active',g.active,
      'merchant_id',g.merchant_id,'metadata',g.metadata,
      'branch_ids',coalesce((select jsonb_agg(gm.branch_id order by gm.branch_id) from private.branch_group_members_v1 gm where gm.group_id=g.id),'[]'::jsonb)
    ) order by g.name
  ),'[]'::jsonb) into v_groups
  from private.branch_groups_v1 g where g.tenant_id=v_tenant_id;

  return jsonb_build_object(
    'tenant',v_tenant,
    'summary',coalesce(v_summary,'{}'::jsonb),
    'merchants',v_merchants,
    'groups',v_groups,
    'generated_at',now()
  );
end;
$$;

