create or replace function public.set_branch_channel_v1(
  p_branch_id uuid,
  p_channel text,
  p_enabled boolean,
  p_reason text default null,
  p_message_ar text default null
)
returns jsonb
language plpgsql
security definer
set search_path=''
as $$
declare
  v_tenant_id uuid;
  v_before jsonb;
  v_after jsonb;
begin
  if p_channel not in ('pos','online_sales','customer_app','marketplace','delivery','pickup') then
    raise exception using errcode='22023',message='INVALID_BRANCH_CHANNEL';
  end if;
  select b.tenant_id into v_tenant_id from public.branches b where b.id=p_branch_id;
  if v_tenant_id is null then raise exception using errcode='P0002',message='BRANCH_NOT_FOUND'; end if;
  if not public.can_manage_business_structure_v1(v_tenant_id) then raise exception using errcode='42501',message='BUSINESS_STRUCTURE_MANAGER_REQUIRED'; end if;
  if not p_enabled and nullif(btrim(coalesce(p_reason,'')),'') is null then raise exception using errcode='22023',message='DISABLE_REASON_REQUIRED'; end if;

  perform pg_advisory_xact_lock(hashtext(p_branch_id::text||':'||p_channel));
  v_before:=private.branch_channel_runtime_v1(p_branch_id,p_channel);

  insert into private.branch_channel_controls_v1(branch_id,channel,configured_enabled,reason,message_ar,source,revision,updated_by,updated_at)
  values(p_branch_id,p_channel,p_enabled,p_reason,p_message_ar,'manual',1,auth.uid(),now())
  on conflict(branch_id,channel) do update set
    configured_enabled=excluded.configured_enabled,
    reason=excluded.reason,
    message_ar=excluded.message_ar,
    source='manual',
    revision=private.branch_channel_controls_v1.revision+1,
    updated_by=auth.uid(),updated_at=now();

  if p_channel='delivery' then
    update public.branches set delivery_enabled=p_enabled,updated_at=now() where id=p_branch_id;
  elsif p_channel='marketplace' and not p_enabled then
    update public.branches set marketplace_customer_enabled=false,updated_at=now() where id=p_branch_id;
  end if;

  v_after:=private.branch_channel_runtime_v1(p_branch_id,p_channel);
  insert into private.business_structure_audit_v1(tenant_id,entity_type,entity_id,branch_id,action,before_state,after_state,reason,actor_user_id)
  values(v_tenant_id,'branch_channel',p_branch_id,p_branch_id,case when p_enabled then 'enable' else 'disable' end,v_before,v_after,p_reason,auth.uid());
  return v_after;
end;
$$;

revoke all on function public.set_branch_channel_v1(uuid,text,boolean,text,text) from public, anon;
grant execute on function public.set_branch_channel_v1(uuid,text,boolean,text,text) to authenticated, service_role;

create or replace function public.create_branch_group_v1(
  p_tenant_id uuid,
  p_code text,
  p_name text,
  p_group_type text default 'custom',
  p_merchant_id uuid default null,
