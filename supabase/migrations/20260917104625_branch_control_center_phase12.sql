create or replace function private.branch_channel_runtime_v1(p_branch_id uuid, p_channel text)
returns jsonb
language plpgsql
stable
security definer
set search_path=''
as $$
declare
  v_branch public.branches%rowtype;
  v_merchant public.merchants%rowtype;
  v_control private.branch_channel_controls_v1%rowtype;
  v_configured boolean;
  v_effective boolean := true;
  v_blocked jsonb := '[]'::jsonb;
  v_platform boolean;
begin
  if p_channel not in ('pos','online_sales','customer_app','marketplace','delivery','pickup') then
    raise exception using errcode='22023', message='INVALID_BRANCH_CHANNEL';
  end if;

  select * into v_branch from public.branches where id=p_branch_id;
  if v_branch.id is null then
    raise exception using errcode='P0002', message='BRANCH_NOT_FOUND';
  end if;
  select * into v_merchant from public.merchants where id=v_branch.merchant_id;
  if v_merchant.id is null then
    raise exception using errcode='P0002', message='BRANCH_MERCHANT_NOT_FOUND';
  end if;

  select * into v_control
  from private.branch_channel_controls_v1
  where branch_id=p_branch_id and channel=p_channel;

  v_configured := coalesce(v_control.configured_enabled,
    case p_channel
      when 'pos' then coalesce(v_branch.active,false)
      when 'online_sales' then coalesce(v_branch.active,false) and v_merchant.merchant_type='owned'
      when 'customer_app' then coalesce(v_branch.active,false) and v_merchant.merchant_type='owned'
      when 'marketplace' then coalesce(v_branch.marketplace_customer_enabled,false)
      when 'delivery' then coalesce(v_branch.delivery_enabled,false)
      when 'pickup' then false
      else false
    end
  );

  if not v_configured then
    v_effective:=false;
    v_blocked:=v_blocked || jsonb_build_array('branch_channel_disabled');
  end if;
  if not coalesce(v_branch.active,false) then
    v_effective:=false;
    v_blocked:=v_blocked || jsonb_build_array('branch_inactive');
  end if;
  if v_merchant.status <> 'active' then
    v_effective:=false;
    v_blocked:=v_blocked || jsonb_build_array('merchant_inactive');
  end if;

  if p_channel='pos' then
    v_platform:=private.tenant_capability_enabled_v1(v_branch.tenant_id,'pos');
    if not v_platform then v_effective:=false; v_blocked:=v_blocked||jsonb_build_array('tenant_pos_disabled'); end if;
  elsif p_channel='online_sales' then
    v_platform:=private.tenant_capability_enabled_v1(v_branch.tenant_id,'online_sales');
    if not v_platform then v_effective:=false; v_blocked:=v_blocked||jsonb_build_array('tenant_online_sales_disabled'); end if;
    v_platform:=private.tenant_capability_enabled_v1(v_branch.tenant_id,'customer_app');
    if not v_platform then v_effective:=false; v_blocked:=v_blocked||jsonb_build_array('tenant_customer_app_disabled'); end if;
  elsif p_channel='customer_app' then
    v_platform:=private.tenant_capability_enabled_v1(v_branch.tenant_id,'customer_app');
    if not v_platform then v_effective:=false; v_blocked:=v_blocked||jsonb_build_array('tenant_customer_app_disabled'); end if;
  elsif p_channel='marketplace' then
    v_platform:=private.tenant_capability_enabled_v1(v_branch.tenant_id,'online_sales');
    if not v_platform then v_effective:=false; v_blocked:=v_blocked||jsonb_build_array('tenant_online_sales_disabled'); end if;
    v_platform:=private.tenant_capability_enabled_v1(v_branch.tenant_id,'customer_app');
    if not v_platform then v_effective:=false; v_blocked:=v_blocked||jsonb_build_array('tenant_customer_app_disabled'); end if;
    if v_merchant.merchant_type not in ('partner','franchise') then
      v_effective:=false; v_blocked:=v_blocked||jsonb_build_array('merchant_not_marketplace');
    end if;
    if v_merchant.customer_published_at is null then
      v_effective:=false; v_blocked:=v_blocked||jsonb_build_array('merchant_not_published');
    end if;
    if not coalesce(v_branch.marketplace_customer_enabled,false) then
      v_effective:=false; v_blocked:=v_blocked||jsonb_build_array('branch_not_marketplace_published');
    end if;
  elsif p_channel='delivery' then
    v_platform:=private.tenant_capability_enabled_v1(v_branch.tenant_id,'delivery');
    if not v_platform then v_effective:=false; v_blocked:=v_blocked||jsonb_build_array('tenant_delivery_disabled'); end if;
    if not coalesce(v_branch.delivery_enabled,false) then
      v_effective:=false; v_blocked:=v_blocked||jsonb_build_array('legacy_delivery_disabled');
    end if;
  elsif p_channel='pickup' then
    v_platform:=private.tenant_capability_enabled_v1(v_branch.tenant_id,'online_sales');
    if not v_platform then v_effective:=false; v_blocked:=v_blocked||jsonb_build_array('tenant_online_sales_disabled'); end if;
    v_platform:=private.tenant_capability_enabled_v1(v_branch.tenant_id,'customer_app');
    if not v_platform then v_effective:=false; v_blocked:=v_blocked||jsonb_build_array('tenant_customer_app_disabled'); end if;
  end if;

  return jsonb_build_object(
    'branch_id',v_branch.id,
    'tenant_id',v_branch.tenant_id,
    'merchant_id',v_branch.merchant_id,
    'merchant_type',v_merchant.merchant_type,
    'channel',p_channel,
    'configured_enabled',v_configured,
    'effective_enabled',v_effective,
    'blocked_by',v_blocked,
    'reason',v_control.reason,
    'message_ar',v_control.message_ar,
    'source',coalesce(v_control.source,'legacy_fallback'),
    'revision',coalesce(v_control.revision,0),
    'updated_at',v_control.updated_at
  );
end;
$$;

