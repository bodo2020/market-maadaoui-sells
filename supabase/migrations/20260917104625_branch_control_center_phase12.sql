create or replace function public.set_branch_group_members_v1(p_group_id uuid,p_branch_ids uuid[])
returns jsonb
language plpgsql
security definer
set search_path=''
as $$
declare
  v_group private.branch_groups_v1%rowtype;
  v_bad integer;
  v_before jsonb;
  v_after jsonb;
begin
  select * into v_group from private.branch_groups_v1 where id=p_group_id for update;
  if v_group.id is null then raise exception using errcode='P0002',message='BRANCH_GROUP_NOT_FOUND'; end if;
  if not public.can_manage_business_structure_v1(v_group.tenant_id) then raise exception using errcode='42501',message='BUSINESS_STRUCTURE_MANAGER_REQUIRED'; end if;

  select count(*) into v_bad
  from unnest(coalesce(p_branch_ids,'{}'::uuid[])) x(branch_id)
  left join public.branches b on b.id=x.branch_id
  where b.id is null or b.tenant_id<>v_group.tenant_id or (v_group.merchant_id is not null and b.merchant_id<>v_group.merchant_id);
  if v_bad>0 then raise exception using errcode='22023',message='BRANCH_GROUP_SCOPE_MISMATCH'; end if;

  select coalesce(jsonb_agg(gm.branch_id order by gm.branch_id),'[]'::jsonb) into v_before
  from private.branch_group_members_v1 gm where gm.group_id=p_group_id;

  delete from private.branch_group_members_v1 where group_id=p_group_id;
  insert into private.branch_group_members_v1(group_id,branch_id,created_by)
  select p_group_id,x.branch_id,auth.uid()
  from (select distinct unnest(coalesce(p_branch_ids,'{}'::uuid[])) as branch_id) x;

  update private.branch_groups_v1 set updated_by=auth.uid(),updated_at=now() where id=p_group_id;
  select coalesce(jsonb_agg(gm.branch_id order by gm.branch_id),'[]'::jsonb) into v_after
  from private.branch_group_members_v1 gm where gm.group_id=p_group_id;

  insert into private.business_structure_audit_v1(tenant_id,entity_type,entity_id,action,before_state,after_state,actor_user_id)
  values(v_group.tenant_id,'branch_group_members',p_group_id,'replace_members',v_before,v_after,auth.uid());
  return jsonb_build_object('group_id',p_group_id,'branch_ids',v_after);
end;
$$;

